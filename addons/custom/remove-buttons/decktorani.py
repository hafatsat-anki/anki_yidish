class DeckSelectorDialog(QDialog):
    def __init__(self, parent, deck_list):
        super().__init__(parent)
        self.deck_list = deck_list
        self.selected_decks = []
        self.setWindowTitle("קלייבט אויס פעקלעך צו שאפן")
        self.setMinimumSize(400, 500)
        self.setLayout(QVBoxLayout())

        # הסבר קצר
        label = QLabel("קלייבט אויס די פעקלעך וואס איר ווילט שאפן. מען קען עפענען דעם בוים און אויסקלייבן אונטערפעקלעך.")
        label.setWordWrap(True)
        self.layout().addWidget(label)

        # יצירת העץ
        self.tree = QTreeWidget()
        self.tree.setHeaderHidden(True)
        self.tree.setLayoutDirection(Qt.LayoutDirection.RightToLeft)
        self.layout().addWidget(self.tree)

        # כפתורים - תיקון לשגיאת Qt6
        # שימוש ב-StandardButton חובה בגרסאות חדשות
        buttons = QDialogButtonBox(QDialogButtonBox.StandardButton.Ok | QDialogButtonBox.StandardButton.Cancel)
        buttons.accepted.connect(self.accept)
        buttons.rejected.connect(self.reject)

        # תרגום כפתורים לעברית
        buttons.button(QDialogButtonBox.StandardButton.Ok).setText("שאף פעקלעך")
        buttons.button(QDialogButtonBox.StandardButton.Cancel).setText("אפזאגן")

        self.layout().addWidget(buttons)

        self.populate_tree()

    def populate_tree(self):
        # מיון הרשימה כדי שהעץ ייראה מסודר
        sorted_decks = sorted(self.deck_list)

        # מילון לשמירת הפניות לצמתים שנוצרו
        created_nodes = {}

        for deck_path in sorted_decks:
            parts = deck_path.split("::")
            current_path = ""
            parent_node = self.tree.invisibleRootItem()

            for i, part in enumerate(parts):
                if i > 0:
                    current_path += "::" + part
                else:
                    current_path = part

                if current_path not in created_nodes:
                    node = QTreeWidgetItem(parent_node)
                    node.setText(0, part)
                    # הגדרת תיבת סימון
                    node.setCheckState(0, Qt.CheckState.Unchecked) # שימוש ב-Qt.CheckState.Unchecked ליתר ביטחון ב-Qt6
                    # הגדרת התנהגות אוטומטית (בחירת הורה בוחרת ילדים וכו')
                    node.setFlags(node.flags() | Qt.ItemFlag.ItemIsUserCheckable | Qt.ItemFlag.ItemIsAutoTristate)

                    created_nodes[current_path] = node
                    parent_node = node
                else:
                    parent_node = created_nodes[current_path]

    def get_selected(self):
        """ברענגט צוריק א ליסטע פון אלע אנגעצייכנטע פולע וועגן"""
        selected = []

        def traverse(item, path_so_far):
            text = item.text(0)
            current_path = f"{path_so_far}::{text}" if path_so_far else text

            # בדיקת מצב הסימון - תמיכה בגרסאות ישנות וחדשות של Qt
            check_state = item.checkState(0)
            # ב-Qt6 לפעמים זה אובייקט Enum ולפעמים מספר, ההשוואה הזו בטוחה
            if check_state == Qt.CheckState.Checked or check_state == 2:
                selected.append(current_path)

            # המשך לילדים
            for i in range(item.childCount()):
                traverse(item.child(i), current_path)

        root = self.tree.invisibleRootItem()
        for i in range(root.childCount()):
            traverse(root.child(i), "")

        return selected

