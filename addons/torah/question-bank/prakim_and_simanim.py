def get_perek_or_siman(without_prakim, filename):
    # #203 - imported archive paths use '/', so normalize before detecting Shas and extracting the basename.
    normalized_filename = filename.replace("\\", "/")
    filename_parts = normalized_filename.split("/")
    file_basename = filename_parts[-1]
    if without_prakim[-1].split("%")[0] in shua:  #שו"ע
        mas = without_prakim[-1].split("%")[0]
        daf = file_basename.replace("סימן_", "").split("_")[0].replace(".txt", "")
        prakim_by_masechet = shua.get(mas).items()
        count = len(prakim_by_masechet)
        for perek, start in reversed(prakim_by_masechet):
            if letters_to_num(daf) >= letters_to_num(start):
                num = count if count > 9 else f"0{count}"
                return f"{num}{perek}", SUBJECT_TYPES.SHUA
            count -= 1
    elif "חלק" in without_prakim[-1]:  # משנ"ב
        daf = file_basename.replace(".txt", "").split("_")[1]
        prakim_by_masechet = shua["אורח חיים"].items()
        count = len(prakim_by_masechet)
        for perek, start in reversed(prakim_by_masechet):
            if letters_to_num(daf) >= letters_to_num(start):
                num = count if count > 9 else f"0{count}"
                return f"{num}{perek}", SUBJECT_TYPES.MISHNAB

            count -= 1
    elif "שס" in filename_parts:  # ש"ס
        mas = without_prakim[-1][2:].split("%")[0]
        if mas in sdarim or "38קנים" in filename or "39מדות" in filename or "עדיות" in filename:
            return "", SUBJECT_TYPES.SHAS
        elif without_prakim[-1] == "36מעילה ואחריו":
            mas = without_prakim[-1][2:].split(" ")[0]
        daf = file_basename.split("_")[-1].replace(".txt", "")
        prakim_by_masechet = shas.get(mas).items()
        count = len(prakim_by_masechet)
        for perek, start in reversed(prakim_by_masechet):
            if letters_to_num(daf) >= letters_to_num(start):
                num = count if count > 9 else f"0{count}"
                return f"{num}{perek}", SUBJECT_TYPES.SHAS
            count -= 1
        return "", SUBJECT_TYPES.SHAS
    else:
        return "", SUBJECT_TYPES.OTHER
