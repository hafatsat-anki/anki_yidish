"""#362 - א סארטיר-שליסל פאר טעקסט מיט די באזונדערע גימטריא-צייכנס טו/טז.

ביי גימטריא שרייבט מען געווענליך נישט 15/16 אלס "יה"/"יו" (צוליב כבוד השם), נאר מען נוצט
אנשטאט דעם "טו"/"טז". דער פראבלעם: אינעם אלף-בית קומט ט' פאר י', דעריבער
שטעלט א געווענליכע אלפאבעטישע סארטירונג "טו"/"טז" *פאר* "יא".."יד" (11-14), אנשטאט נאך זיי
(15,16 > 11-14). דאס איז דער איינציקער צאל-אויסנאם אינעם געווענליכן תחום; אלע אנדערע צירופים
(א..י, יא..יד, יז..יט, כ...) ווערן שוין ריכטיג אלפאבעטיש סארטירט, ווייל דער סדר פון די אותיות
אינעם אלף-בית שטימט מיטן סדר פון זייערע גימטריא-ווערטן.

די לייזונג: נאר פארן סארטירן (נישט פארן ווייזן) פארבייט מען יעדן זעלבסטשטענדיגן צירוף (וואס איז נישט צוגעקלעבט
צו אן אנדער אות) פון "טו"/"טז" מיט "יה"/"יו", לויטן סדר. אזוי שטעלט די געווענליכע אלפאבעטישע פארגלייכונג
זיי ריכטיג צווישן יד' און יז'. מען פארוואנדלט דא נישט יעדע גימטריא
אין א צאל; דאס איז א צילגעריכטע הרחבה פאר די צוויי אויסנאמען וואס דער באנוצער האט געבעטן.
"""

import re

# א גילטיגע גימטריא-פארצייכענונג פאר הונדערטער/טויזנטער: ת ווערט איבערגעחזרט (400/800/1200), און דערנאך קען קומען ק/ר/ש
# (100/200/300), לויט די צירופים פון #362: טו,קטו,רטו,תטו,תקטו...,תתטו,תתקטו...,תתתטו
# (און אזוי אויך פאר טז). די פארצייכענונג איז א טייל פונעם גאנצן טעקסט-צייכן, דעריבער ווערט דער גרענעץ "נישט קיין אות" געפרופט
# אויסער דער פארצייכענונג, און נישט גלייך נעבן ט אליין.
_PREFIX = r"ת*[קרש]?"
_TET_VAV = re.compile(rf"(?<![א-ת])({_PREFIX})טו(?![א-ת])")
_TET_ZAYIN = re.compile(rf"(?<![א-ת])({_PREFIX})טז(?![א-ת])")


def gimatria_sort_key(text: str) -> str:
    """גיט צוריק text נאכן פארבייטן זעלבסטשטענדיגע טו/טז מיט יה/יו, נאר אלס א סארטיר-שליסל."""
    if not text:
        return text
    result = _TET_VAV.sub(lambda m: m.group(1) + "יה", text)
    result = _TET_ZAYIN.sub(lambda m: m.group(1) + "יו", result)
    return result
